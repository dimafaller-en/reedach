// Builds the WordPress plugin folder `reedach/`: the editor script with the Reedach core inside,
// the list of rule categories for the settings page, and the notice about sources.
//   node build.mjs          — build
//   node build.mjs --check  — fail if the plugin version differs from package.json
import {build} from 'esbuild';
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {CATEGORIES} from 'reedach';

const here = new URL('.', import.meta.url), root = new URL('../../', import.meta.url);
const {version} = JSON.parse(readFileSync(new URL('package.json', here)));
const php = readFileSync(new URL('reedach/reedach.php', here), 'utf8'), readme = readFileSync(new URL('reedach/readme.txt', here), 'utf8');
const versions = [php.match(/^ \* Version:\s+(\S+)/m)?.[1], php.match(/'REEDACH_VERSION', '([^']+)'/)?.[1], readme.match(/^Stable tag:\s+(\S+)/m)?.[1]];
if (versions.some(v => v !== version)) throw new Error(`plugin versions ${versions.join(', ')} differ from package.json ${version}`);
if (process.argv.includes('--check')) process.exit(0);

// The italic e of the logo, as the sidebar icon.
const e = readFileSync(new URL('docs/logo/reedach-icon.svg', root), 'utf8').match(/<path d="([^"]+)" fill/g)[0].match(/d="([^"]+)"/)[1];

await build({
 entryPoints: [fileURLToPath(new URL('src/editor.js', here))],
 outfile: fileURLToPath(new URL('reedach/build/editor.js', here)),
 bundle: true, format: 'iife', target: 'es2020', charset: 'utf8', legalComments: 'inline',
 define: {REEDACH_ICON_E: JSON.stringify(e)},
 banner: {js: `/* Reedach ${version} for WordPress — https://github.com/dimafaller-en/reedach. Source: packages/wordpress/src. Includes the Reedach core (MIT). */`},
});

mkdirSync(new URL('reedach/includes/', here), {recursive: true});
const q = s => "'" + String(s).replace(/[\\']/g, '\\$&') + "'";
writeFileSync(new URL('reedach/includes/categories.php', here),
 `<?php\n// Generated by build.mjs from the Reedach rules. Do not edit.\n\nif ( ! defined( 'ABSPATH' ) ) {\n\texit;\n}\n\nreturn array(\n${Object.entries(CATEGORIES).sort((a, b) => a[1].replace(/[«»]/g, '').localeCompare(b[1].replace(/[«»]/g, ''), 'ru')).map(([k, v]) => `\t${q(k)} => ${q(v)},`).join('\n')}\n);\n`);
writeFileSync(new URL('reedach/NOTICE.txt', here), readFileSync(new URL('NOTICE.md', root)));
console.log(`reedach ${version}: build/editor.js, includes/categories.php, NOTICE.txt`);
